    val bookmarks: Flow<List<QuranBookmarkEntity>> = bookmarkDao.getAllBookmarks()

    suspend fun toggleBookmark(surah: Surah, ayahNumber: Int) {
        if (bookmarkDao.isBookmarked(surah.number, ayahNumber)) {
            bookmarkDao.removeSpecificBookmark(surah.number, ayahNumber)
        } else {
            bookmarkDao.insertBookmark(
                QuranBookmarkEntity(
                    surahNumber = surah.number,
                    ayahNumber = ayahNumber,
                    surahNameBn = surah.nameBn,
                    surahNameAr = surah.nameAr
                )
            )
        }
    }

    suspend fun isBookmarked(surahNumber: Int, ayahNumber: Int): Boolean {
        return bookmarkDao.isBookmarked(surahNumber, ayahNumber)
    }
